from pathlib import Path

EVAL_RESULTS: list[dict[str, str]] = []


def record_eval_result(
    scenario_id: str,
    scenario_name: str,
    expected: str,
    actual: str,
    passed: bool,
    notes: str,
) -> None:
    entry = {
        "scenario": f"{scenario_id}: {scenario_name}",
        "expected": expected,
        "actual": actual,
        "status": "PASS" if passed else "FAIL",
        "notes": notes,
    }
    # Deduplicate by scenario prefix if run multiple times in same process
    for idx, existing in enumerate(EVAL_RESULTS):
        if existing["scenario"].startswith(f"{scenario_id}:"):
            EVAL_RESULTS[idx] = entry
            return
    EVAL_RESULTS.append(entry)


def pytest_sessionfinish(session, exitstatus):
    if not EVAL_RESULTS:
        return
    # Write to root EVAL_REPORT.md
    root_report = Path(__file__).resolve().parent.parent.parent / "EVAL_REPORT.md"
    lines = [
        "# Automated Evaluation Report (Generated by Test Run)",
        "",
        f"- **Total Scenarios & Regressions Executed:** {len(EVAL_RESULTS)}",
        f"- **Passed:** {sum(1 for r in EVAL_RESULTS if r['status'] == 'PASS')}",
        f"- **Failed:** {sum(1 for r in EVAL_RESULTS if r['status'] == 'FAIL')}",
        "- **Execution Mode:** Offline Deterministic Scripted LLM (`LLM_MODE=offline` via `ScriptedEvalLLM`)",
        "",
        "| Scenario | Expected | Actual | Pass/Fail | Notes |",
        "|---|---|---|---|---|",
    ]
    for r in EVAL_RESULTS:
        lines.append(
            f"| {r['scenario']} | {r['expected']} | {r['actual']} | **{r['status']}** | {r['notes']} |"
        )
    root_report.write_text("\n".join(lines) + "\n", encoding="utf-8")
